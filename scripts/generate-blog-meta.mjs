/**
 * scripts/generate-blog-meta.mjs
 *
 * Generates src/data/blogPostsMeta.ts from blogPosts.ts.
 * Strips `content`, `seoTitle`, and `seoDescription` from every post,
 * leaving only the lightweight metadata fields needed by listing components.
 *
 * Run: node scripts/generate-blog-meta.mjs
 */

import { build } from "esbuild";
import { createRequire } from "module";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const TMP = path.join(ROOT, "node_modules", ".cache", "blog-meta-gen.cjs");
const OUT = path.join(ROOT, "src", "data", "blogPostsMeta.ts");

// 1. Bundle blogPosts.ts to a CJS module we can require()
await build({
  entryPoints: [path.join(ROOT, "src", "data", "blogPosts.ts")],
  bundle: true,
  format: "cjs",
  outfile: TMP,
  platform: "node",
  tsconfig: path.join(ROOT, "tsconfig.json"),
  logLevel: "silent",
});

// 2. Load the bundle and strip heavy fields
const require = createRequire(import.meta.url);
// Clear require cache in case this script was run before
delete require.cache[require.resolve(TMP)];
const { blogPosts } = require(TMP);

const metaPosts = blogPosts.map(
  ({ content, seoTitle, seoDescription, ...rest }) => rest
);

// 3. Serialize to TypeScript source
function serialize(val, indent = 2) {
  const pad = " ".repeat(indent);
  if (val === null) return "null";
  if (val === undefined) return "undefined";
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "number" || typeof val === "boolean") return String(val);
  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";
    const items = val.map((v) => pad + "  " + serialize(v, indent + 2));
    return `[\n${items.join(",\n")},\n${pad}]`;
  }
  if (typeof val === "object") {
    const entries = Object.entries(val)
      .filter(([, v]) => v !== undefined)
      .map(([k, v]) => `${pad}  ${k}: ${serialize(v, indent + 2)}`);
    return `{\n${entries.join(",\n")},\n${pad}}`;
  }
  return JSON.stringify(val);
}

const postsTs = metaPosts
  .map((p) => `  ${serialize(p, 2)}`)
  .join(",\n");

const output = `// AUTO-GENERATED by scripts/generate-blog-meta.mjs
// Do NOT edit directly — run: node scripts/generate-blog-meta.mjs
// This file contains lightweight metadata for all blog posts (no content, no seoTitle/Description).
// Listing components (Blog, SPCTA, FeaturedInsightsHub) import from here.
// BlogPost.tsx imports the full blogPosts.ts (lazy route — only loads when a post is opened).

export interface BlogPostMeta {
  id: string;
  slug: string;
  title: string;
  excerpt: string;
  date: string;
  dateISO: string;
  readTime: string;
  image: string;
  category: string;
  tags: string[];
  hasDashboard?: string;
  relatedSlugs?: string[];
  locale?: "en" | "no" | "sv" | "fi" | "da";
  translationGroup?: string;
}

export const blogPostsMeta: BlogPostMeta[] = [
${postsTs},
];

export function getBlogPostMetaBySlug(slug: string): BlogPostMeta | undefined {
  return blogPostsMeta.find((p) => p.slug === slug);
}

export function getRecentBlogPostsMeta(count = 4): BlogPostMeta[] {
  return blogPostsMeta.slice(0, count);
}
`;

fs.writeFileSync(OUT, output, "utf-8");
const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log(`✅  Written ${OUT} (${kb} KB, ${metaPosts.length} posts)`);

// Clean up temp file
fs.unlinkSync(TMP);
